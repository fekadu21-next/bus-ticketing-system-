import verifierRepository from '../../repository/verifier/verifier.repository.js';
import ApiError from '../../utils/apiError.js';
import { ROLES } from '../../constants/index.js';
import jwt from 'jsonwebtoken';
import env from '../../Config/env.js';
import notificationService from '../notification.service.js';
import { NOTIFICATION_TYPES, NOTIFICATION_PRIORITIES } from '../../constants/notification.js';

export class VerifierService {
  resolveVerifierOrg(user) {
    if (!user) {
      throw new ApiError(401, 'User context missing.');
    }

    if (user.roles?.includes(ROLES.ADMIN)) {
      return user.orgContexts?.[0]?.organizationId || user.organizationId || null;
    }

    const verifierContext =
      user.orgContexts?.find((c) => c.role === ROLES.TICKET_VERIFIER || c.role === 'VERIFIER') ||
      user.orgContexts?.[0];

    const orgId =
      verifierContext?.organizationId ||
      user.organizationId ||
      user.organizationContext?.[0]?.organizationId;

    if (!orgId && !user.roles?.includes(ROLES.ADMIN)) {
      throw new ApiError(403, 'Forbidden: Verifier is not assigned to any active organization.');
    }

    return orgId || null;
  }

  async getAssignedTrips(user, query) {
    const orgId = this.resolveVerifierOrg(user);
    if (!orgId) {
      throw new ApiError(400, 'Verifier organization context is required.');
    }

    return verifierRepository.findTripsForOrganization(orgId, query);
  }

  async getTripManifest(user, tripId) {
    const orgId = this.resolveVerifierOrg(user);

    const trip = await verifierRepository.findTripById(tripId, orgId);
    if (!trip) {
      throw new ApiError(404, 'Trip not found or does not belong to your organization.');
    }

    return {
      trip: {
        id: trip.id,
        route: trip.routes,
        bus: trip.buses,
        departureTime: trip.departure_time,
        status: trip.status,
      },
      passengerManifest: trip.tickets.map((t) => ({
        ticketId: t.id,
        ticketNumber: t.ticket_number,
        seatNumber: t.seat_number,
        status: t.status,
        passengerName: `${t.passenger?.first_name || ''} ${t.passenger?.last_name || ''}`.trim(),
        phone: t.passenger?.phone,
        verifiedAt: t.verified_at,
      })),
    };
  }

  async verifyTicket(user, { qrToken, qrCode, tripId }) {
    const isAdmin = Boolean(user?.roles?.includes(ROLES.ADMIN));
    const orgId = this.resolveVerifierOrg(user);

    const cleanInput = String(qrToken || qrCode || '').trim();
    if (!cleanInput) {
      return {
        valid: false,
        status: 'INVALID',
        message: 'Ticket QR code or number is required.',
      };
    }

    // 1. Try parsing JSON if input is JSON (like the QR codes generated by mobile and web)
    let parsedJson = null;
    if (cleanInput.startsWith('{') && cleanInput.endsWith('}')) {
      try {
        parsedJson = JSON.parse(cleanInput);
      } catch {
        // Not valid JSON, continue with raw string
      }
    }

    // 2. Decode JWT if input is a JWT or if JSON has a JWT
    let decodedToken = null;
    const jwtCandidate = parsedJson?.qrToken || parsedJson?.qr_token || cleanInput;
    if (typeof jwtCandidate === 'string' && jwtCandidate.startsWith('eyJ')) {
      try {
        decodedToken = jwt.verify(jwtCandidate, env.jwt.accessSecret);
      } catch {
        try {
          decodedToken = jwt.decode(jwtCandidate);
        } catch {
          // Ignore
        }
      }
    }

    // 3. Extract candidate identifiers
    const extractedTicketId =
      decodedToken?.ticketId ||
      parsedJson?.ticketId ||
      parsedJson?.ticket_id ||
      parsedJson?.id ||
      (/^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i.test(cleanInput)
        ? cleanInput
        : null);

    const extractedTicketNumber =
      decodedToken?.ticketNumber ||
      parsedJson?.ticketNumber ||
      parsedJson?.ticket_number ||
      cleanInput;

    const extractedBookingId =
      decodedToken?.bookingId ||
      parsedJson?.bookingId ||
      parsedJson?.booking_id ||
      null;

    const extractedSeatNumber =
      decodedToken?.seatNumber ||
      parsedJson?.seatNumber ||
      parsedJson?.seat_number ||
      null;

    // 4. Clean ticket number if it contains formatting prefixes/suffixes
    // e.g. "Ticket #TKT-123" -> "TKT-123"
    // e.g. "SECURE-PASS-TKT-123-SEAT5" -> "TKT-123"
    // e.g. "TKT-123-S5" -> "TKT-123"
    let cleanTicketNumber = extractedTicketNumber;
    if (typeof cleanTicketNumber === 'string') {
      cleanTicketNumber = cleanTicketNumber
        .replace(/^Ticket\s*[:#\s]?\s*/i, '')
        .replace(/^SECURE-PASS-/i, '')
        .replace(/-(SEAT|S)\d+$/i, '')
        .trim();
    }

    // 5. Look up ticket using all resolved identifiers
    let ticket = null;
    if (extractedTicketId) {
      ticket = await verifierRepository.findTicketById(extractedTicketId);
    }
    if (!ticket) {
      ticket = await verifierRepository.findTicketByIdentifiers({
        ticketId: extractedTicketId,
        ticketNumber: extractedTicketNumber,
        cleanTicketNumber,
        qrToken: cleanInput,
        bookingId: extractedBookingId,
        seatNumber: extractedSeatNumber,
      });
    }

    // 6. INVALID: If ticket is not found in database or invalid QR
    if (!ticket) {
      await verifierRepository.createVerificationAuditRecord({
        ticketId: null,
        bookingId: null,
        tripId: tripId || null,
        verifierId: user.id,
        organizationId: orgId,
        result: 'INVALID',
        notes: `Unrecognized or forged QR code: ${cleanInput.slice(0, 80)}`,
      });

      return {
        valid: false,
        status: 'INVALID',
        message: 'Invalid or unrecognized ticket QR code / number.',
      };
    }

    const effectiveTripId = tripId || ticket.trip_id;

    // 7. Organization boundary check: Ticket belongs to another operator (Admin bypasses)
    const ticketOrgId = ticket.organization_id || ticket.trips?.organization_id;
    if (!isAdmin && orgId && ticketOrgId && ticketOrgId !== orgId) {
      await verifierRepository.createVerificationAuditRecord({
        ticketId: ticket.id,
        bookingId: ticket.booking_id,
        tripId: effectiveTripId,
        verifierId: user.id,
        organizationId: orgId,
        result: 'INVALID',
        notes: `Ticket belongs to organization ${ticketOrgId}, not verifier organization ${orgId}`,
      }).catch(() => {});

      throw new ApiError(403, 'Forbidden: You cannot verify tickets belonging to another organization.');
    }

    // 8. Verify trip exists and belongs to verifier organization
    if (tripId) {
      const targetTrip = await verifierRepository.findTripById(tripId, null);
      if (targetTrip && orgId && targetTrip.organization_id !== orgId && !isAdmin) {
        throw new ApiError(403, 'Forbidden: You cannot verify trips belonging to another organization.');
      }
    }

    const trip = await verifierRepository.findTripById(effectiveTripId, isAdmin ? null : orgId);
    if (!trip) {
      throw new ApiError(404, 'Trip not found.');
    }

    // 9. WRONG_TRIP: Ticket is valid, but attempted boarding for a different trip
    // Only enforced when caller explicitly provided a specific tripId
    if (tripId && ticket.trip_id !== tripId) {
      await verifierRepository.createVerificationAuditRecord({
        ticketId: ticket.id,
        bookingId: ticket.booking_id,
        tripId,
        verifierId: user.id,
        organizationId: orgId || ticketOrgId,
        result: 'WRONG_TRIP',
        notes: `Ticket scheduled for trip ${ticket.trip_id}, attempted boarding for trip ${tripId}`,
      });

      return {
        valid: false,
        status: 'WRONG_TRIP',
        message: 'Ticket is valid, but scheduled for a different trip.',
        ticket: {
          id: ticket.id,
          ticketNumber: ticket.ticket_number,
          seat: `A${ticket.seat_number}`,
          seatNumber: ticket.seat_number,
          scheduledTripId: ticket.trip_id,
        },
      };
    }

    // 6. CANCELLED: Ticket or booking has been cancelled
    if (ticket.status === 'CANCELLED' || ticket.bookings?.status === 'CANCELLED') {
      await verifierRepository.createVerificationAuditRecord({
        ticketId: ticket.id,
        bookingId: ticket.booking_id,
        tripId: effectiveTripId,
        verifierId: user.id,
        organizationId: orgId,
        result: 'CANCELLED',
        notes: 'Attempted boarding with cancelled ticket',
      });

      notificationService.notifyOrganizationStaff(
        orgId,
        [ROLES.BOOKING_COORDINATOR, ROLES.OPERATIONAL_MANAGER],
        {
          type: NOTIFICATION_TYPES.VERIFICATION_UPDATE,
          priority: NOTIFICATION_PRIORITIES.NORMAL,
          title: 'Boarding Alert: Cancelled Ticket Scanned',
          message: `Attempted boarding with cancelled ticket ${ticket.ticket_number} on trip.`,
          metadata: { ticketId: ticket.id, tripId, organizationId: orgId, result: 'CANCELLED' },
        }
      ).catch(() => {});

      return {
        valid: false,
        status: 'CANCELLED',
        message: 'This ticket has been cancelled and cannot be used for boarding.',
      };
    }

    // 7. ALREADY_USED: Ticket has already been scanned/used
    if (ticket.status === 'USED') {
      await verifierRepository.createVerificationAuditRecord({
        ticketId: ticket.id,
        bookingId: ticket.booking_id,
        tripId: effectiveTripId,
        verifierId: user.id,
        organizationId: orgId,
        result: 'ALREADY_USED',
        notes: `Ticket previously verified at ${ticket.verified_at}`,
      });

      return {
        valid: false,
        status: 'ALREADY_USED',
        message: 'This ticket has already been verified.',
      };
    }

    // 8. ATOMIC DOUBLE-VERIFICATION PREVENTION
    const success = await verifierRepository.atomicallyVerifyTicket(ticket.id, user.id);

    if (!success) {
      // Another concurrent verification request won the race
      await verifierRepository.createVerificationAuditRecord({
        ticketId: ticket.id,
        bookingId: ticket.booking_id,
        tripId: effectiveTripId,
        verifierId: user.id,
        organizationId: orgId,
        result: 'ALREADY_USED',
        notes: 'Concurrent verification collision prevented',
      });

      return {
        valid: false,
        status: 'ALREADY_USED',
        message: 'This ticket has already been verified.',
      };
    }

    // 9. VALID: Verification successful
    await verifierRepository.createVerificationAuditRecord({
      ticketId: ticket.id,
      bookingId: ticket.booking_id,
      tripId: effectiveTripId,
      verifierId: user.id,
      organizationId: orgId,
      result: 'VALID',
      notes: 'Passenger boarding permitted',
    });

    if (ticket.passenger_id) {
      await notificationService.safeCreateNotification({
        userId: ticket.passenger_id,
        type: NOTIFICATION_TYPES.TICKET_VERIFIED,
        priority: NOTIFICATION_PRIORITIES.NORMAL,
        title: 'Ticket Verified',
        message: `Your ticket ${ticket.ticket_number} (Seat ${ticket.seat_number}) has been verified for boarding. Have a safe journey!`,
        metadata: {
          ticketId: ticket.id,
          ticketNumber: ticket.ticket_number,
          tripId: effectiveTripId,
          bookingId: ticket.booking_id,
          seatNumber: ticket.seat_number,
          idempotencyKey: `ticket-verify-${ticket.id}`,
        },
      });
    }

    const passengerName = `${ticket.passenger?.first_name || ''} ${ticket.passenger?.last_name || ''}`.trim();

    return {
      valid: true,
      status: 'VALID',
      message: 'Ticket verified successfully. Passenger may board.',
      ticket: {
        id: ticket.id,
        ticketNumber: ticket.ticket_number,
        seat: `A${ticket.seat_number}`,
        seatNumber: ticket.seat_number,
        tripId: ticket.trip_id,
        passenger: {
          id: ticket.passenger?.id,
          name: passengerName,
          email: ticket.passenger?.email,
          phone: ticket.passenger?.phone,
        },
      },
    };
  }

  async getRecentVerifications(user) {
    const orgId = this.resolveVerifierOrg(user);
    return verifierRepository.getRecentVerifications(user.id, orgId);
  }
}

export const verifierService = new VerifierService();
export default verifierService;
